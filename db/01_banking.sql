CREATE OR REPLACE VIEW vw_customer_account_summary AS
SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.city,
    a.account_id,
    a.account_number,
    a.account_type,
    a.balance,
    a.status,
    b.branch_name,
    b.city AS branch_city
FROM Customer c
JOIN Account a ON a.customer_id = c.customer_id
JOIN Branch b ON b.branch_id = a.branch_id;

CREATE OR REPLACE VIEW vw_account_transaction_summary AS
SELECT
    a.account_id,
    a.account_number,
    COUNT(t.transaction_id) AS source_transaction_count,
    COALESCE(SUM(CASE WHEN t.transaction_type='Deposit' THEN t.amount ELSE 0 END),0) AS total_deposits,
    COALESCE(SUM(CASE WHEN t.transaction_type='Withdrawal' THEN t.amount ELSE 0 END),0) AS total_withdrawals,
    COALESCE(SUM(CASE WHEN t.transaction_type='Transfer' THEN t.amount ELSE 0 END),0) AS total_outgoing_transfers,
    a.balance AS current_balance
FROM Account a
LEFT JOIN Bank_Transaction t ON t.account_id = a.account_id
GROUP BY a.account_id, a.account_number, a.balance;

CREATE OR REPLACE VIEW vw_active_loan_summary AS
SELECT
    l.loan_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    l.loan_type,
    l.loan_amount,
    l.interest_rate,
    l.loan_term_months,
    l.remaining_balance,
    l.status,
    b.branch_name,
    COALESCE(SUM(lp.amount),0) AS total_repaid
FROM Loan l
JOIN Customer c ON c.customer_id = l.customer_id
JOIN Branch b ON b.branch_id = l.branch_id
LEFT JOIN Loan_Payment lp ON lp.loan_id = l.loan_id
WHERE l.status IN ('Approved','Active')
GROUP BY l.loan_id, customer_name, l.loan_type, l.loan_amount, l.interest_rate,
         l.loan_term_months, l.remaining_balance, l.status, b.branch_name;

CREATE OR REPLACE VIEW vw_branch_performance AS
SELECT
    b.branch_id,
    b.branch_name,
    b.city,
    COALESCE(a.total_accounts, 0) AS total_accounts,
    COALESCE(a.total_customers, 0) AS total_customers,
    COALESCE(a.total_deposit_balance, 0) AS total_deposit_balance,
    COALESCE(l.total_loans, 0) AS total_loans,
    COALESCE(l.total_loan_amount, 0) AS total_loan_amount,
    COALESCE(l.outstanding_loan_balance, 0) AS outstanding_loan_balance
FROM Branch b
LEFT JOIN (
    SELECT
        branch_id,
        COUNT(*) AS total_accounts,
        COUNT(DISTINCT customer_id) AS total_customers,
        SUM(balance) AS total_deposit_balance
    FROM Account
    GROUP BY branch_id
) a ON a.branch_id = b.branch_id
LEFT JOIN (
    SELECT
        branch_id,
        COUNT(*) AS total_loans,
        SUM(loan_amount) AS total_loan_amount,
        SUM(remaining_balance) AS outstanding_loan_balance
    FROM Loan
    GROUP BY branch_id
) l ON l.branch_id = b.branch_id;


