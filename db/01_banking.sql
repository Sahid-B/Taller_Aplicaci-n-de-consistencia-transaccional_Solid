CREATE PROCEDURE sp_transfer(
 p_from_account VARCHAR(30), p_to_account VARCHAR(30),
 p_amount NUMERIC(15,2), p_description VARCHAR(255),
 p_simulate_error BOOLEAN DEFAULT FALSE
) LANGUAGE plpgsql AS $$
DECLARE
 v_from account%ROWTYPE;
 v_to account%ROWTYPE;
BEGIN
 IF p_amount IS NULL OR p_amount <= 0 THEN
  RAISE EXCEPTION 'El monto debe ser mayor que cero';
 END IF;
 IF p_from_account IS NULL OR p_to_account IS NULL OR p_from_account = p_to_account THEN
  RAISE EXCEPTION 'Seleccione dos cuentas diferentes';
 END IF;
 -- Orden estable para evitar interbloqueos entre transferencias opuestas.
 PERFORM account_id FROM account
 WHERE account_number IN (p_from_account,p_to_account)
 ORDER BY account_id FOR UPDATE;
 SELECT * INTO v_from FROM account WHERE account_number=p_from_account;
 SELECT * INTO v_to FROM account WHERE account_number=p_to_account;
 IF v_from.account_id IS NULL OR v_to.account_id IS NULL
    OR v_from.status <> 'Active' OR v_to.status <> 'Active' THEN
  RAISE EXCEPTION 'Ambas cuentas deben existir y estar activas';
 END IF;
 IF v_from.balance < p_amount THEN
  RAISE EXCEPTION 'Saldo insuficiente';
 END IF;
 UPDATE account SET balance=balance-p_amount WHERE account_id=v_from.account_id;
 IF p_simulate_error THEN
  RAISE EXCEPTION 'Error simulado despues del debito';
 END IF;
 UPDATE account SET balance=balance+p_amount WHERE account_id=v_to.account_id;
 INSERT INTO bank_transaction(account_id,transaction_type,amount,destination_account_id,description)
 VALUES(v_from.account_id,'Transfer',p_amount,v_to.account_id,p_description);
END;
$$;
