-- ======================= TABLES =======================
CREATE TABLE Branch (
    branch_id INT PRIMARY KEY,
    branch_code VARCHAR(20) NOT NULL UNIQUE,
    branch_name VARCHAR(100) NOT NULL,
    address VARCHAR(200),
    city VARCHAR(60) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(120)
);

CREATE TABLE Customer (
    customer_id INT PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    date_of_birth DATE,
    email VARCHAR(120) UNIQUE,
    phone VARCHAR(20),
    address VARCHAR(200),
    city VARCHAR(60),
    province VARCHAR(60),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Account (
    account_id INT PRIMARY KEY,
    account_number VARCHAR(30) NOT NULL UNIQUE,
    customer_id INT NOT NULL,
    branch_id INT NOT NULL,
    account_type VARCHAR(30) CHECK (account_type IN ('Savings','Checking','Current','Fixed Deposit')) NOT NULL,
    opening_balance DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    balance DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    status VARCHAR(30) CHECK (status IN ('Active','Inactive','Closed','Frozen')) NOT NULL DEFAULT 'Active',
    opened_date DATE NOT NULL,
    CONSTRAINT fk_account_customer FOREIGN KEY (customer_id)
        REFERENCES Customer(customer_id),
    CONSTRAINT fk_account_branch FOREIGN KEY (branch_id)
        REFERENCES Branch(branch_id),
    CONSTRAINT chk_account_opening_balance CHECK (opening_balance >= 0),
    CONSTRAINT chk_account_balance CHECK (balance >= 0)
);

CREATE TABLE Bank_Transaction (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INT NOT NULL,
    transaction_type VARCHAR(30) CHECK (transaction_type IN ('Deposit','Withdrawal','Transfer')) NOT NULL,
    amount DECIMAL(15,2) NOT NULL,
    transaction_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    destination_account_id INT NULL,
    description VARCHAR(255),
    CONSTRAINT fk_tx_account FOREIGN KEY (account_id)
        REFERENCES Account(account_id),
    CONSTRAINT fk_tx_destination FOREIGN KEY (destination_account_id)
        REFERENCES Account(account_id),
    CONSTRAINT chk_tx_amount CHECK (amount > 0),
    CONSTRAINT chk_transfer_destination CHECK (
        (transaction_type = 'Transfer' AND destination_account_id IS NOT NULL)
        OR (transaction_type <> 'Transfer' AND destination_account_id IS NULL)
    )
);

CREATE TABLE Loan (
    loan_id INT PRIMARY KEY,
    customer_id INT NOT NULL,
    branch_id INT NOT NULL,
    loan_type VARCHAR(30) CHECK (loan_type IN ('Home','Vehicle','Business','Education','Personal')) NOT NULL,
    loan_amount DECIMAL(15,2) NOT NULL,
    interest_rate DECIMAL(5,2) NOT NULL,
    loan_term_months INT NOT NULL,
    start_date DATE NOT NULL,
    remaining_balance DECIMAL(15,2) NOT NULL,
    status VARCHAR(30) CHECK (status IN ('Pending','Approved','Active','Paid','Defaulted')) NOT NULL DEFAULT 'Pending',
    CONSTRAINT fk_loan_customer FOREIGN KEY (customer_id)
        REFERENCES Customer(customer_id),
    CONSTRAINT fk_loan_branch FOREIGN KEY (branch_id)
        REFERENCES Branch(branch_id),
    CONSTRAINT chk_loan_amount CHECK (loan_amount > 0),
    CONSTRAINT chk_interest_rate CHECK (interest_rate >= 0),
    CONSTRAINT chk_loan_remaining CHECK (remaining_balance >= 0)
);

CREATE TABLE Loan_Payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id INT NOT NULL,
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount DECIMAL(15,2) NOT NULL,
    payment_method VARCHAR(30) CHECK (payment_method IN ('Cash','Account Transfer','Cheque','Online')) NOT NULL,
    CONSTRAINT fk_payment_loan FOREIGN KEY (loan_id)
        REFERENCES Loan(loan_id),
    CONSTRAINT chk_payment_amount CHECK (amount > 0)
);

