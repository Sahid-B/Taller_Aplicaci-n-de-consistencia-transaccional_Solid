-- Recalculate balances from opening balances plus all transaction effects.
-- ================ Aqui se adapto UPDATE JOIN de MySQL a subconsultas PostgreSQL ================
UPDATE account a SET balance = a.opening_balance
 + COALESCE((SELECT SUM(CASE WHEN t.transaction_type='Deposit' THEN t.amount ELSE -t.amount END)
             FROM bank_transaction t WHERE t.account_id=a.account_id),0)
 + COALESCE((SELECT SUM(t.amount) FROM bank_transaction t
             WHERE t.transaction_type='Transfer' AND t.destination_account_id=a.account_id),0);

